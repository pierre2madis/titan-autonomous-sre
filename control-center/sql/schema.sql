-- TITAN Control Center candidate schema
-- Documentation artifact only; not executed.

CREATE SCHEMA IF NOT EXISTS titan;

CREATE TABLE IF NOT EXISTS titan.events (
    event_id TEXT PRIMARY KEY,
    source TEXT,
    event_type TEXT,
    host TEXT,
    correlation_key TEXT,
    observed_at TIMESTAMPTZ,
    received_at TIMESTAMPTZ,
    payload JSONB
);

CREATE TABLE IF NOT EXISTS titan.incident_states (
    incident_id TEXT PRIMARY KEY,
    correlation_key TEXT,
    state TEXT,
    severity TEXT,
    root_event_id TEXT,
    opened_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    resolved_at TIMESTAMPTZ,
    evidence JSONB
);

CREATE TABLE IF NOT EXISTS titan.outbox (
    outbox_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id TEXT,
    topic TEXT,
    payload JSONB,
    created_at TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    attempts INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS titan.transition_inbox (
    event_id TEXT PRIMARY KEY,
    transition_id TEXT,
    incident_id TEXT,
    topic TEXT,
    partition_id INTEGER,
    kafka_offset BIGINT,
    payload JSONB,
    received_at TIMESTAMPTZ
);
